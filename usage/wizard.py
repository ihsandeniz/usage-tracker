# ── adım tablosu ──────────────────────────────────────────────────────────────
#: Adımlar fonksiyon **adıyla** tutuluyor, nesnesiyle değil: tablo import anında bağlansaydı
#: bir adımı yerinden almak (test, ya da ileride bir platform geçersiz kılması) tabloyu değil
#: yalnız modül niteliğini değiştirir ve çağrı eski fonksiyona giderdi — sessizce.
_STEPS = {
    'install':   ('_probe_install',   '_preview_install',   '_do_install',   '_undo_install'),
    'autostart': ('_probe_autostart', '_preview_autostart', '_do_autostart', '_undo_autostart'),
    'shortcut':  ('_probe_shortcut',  '_preview_shortcut',  '_do_shortcut',  '_undo_shortcut'),
    'keys':      ('_probe_keys',      '_preview_keys',      '_do_keys',      '_undo_keys'),
    'verify':    ('_probe_verify',    '_preview_verify',    '_do_verify',    None),
}


def _fn(step: str, slot: int):
    name = _STEPS[step][slot]
    return globals()[name] if name else None

#: `--auto`'nun koşacağı adımlar. `keys` **bilinçli dışarıda**: otomatik mod kullanıcıya
#: sormadan çalışır ve bir anahtarı sormadan yazmanın yolu yoktur.
AUTO_STEPS = ('install', 'autostart', 'shortcut', 'verify')

STEP_TITLES = {
    'install':   'Put the program somewhere permanent',
    'autostart': 'Start it automatically when you log in',
    'shortcut':  'Add a shortcut that opens the panel',
    'keys':      'Provider API keys (optional)',
    'verify':    'Check that everything works',
}


def steps() -> list:
    """Bu makinede anlamlı adımlar, sırayla."""
    return [{'id': sid, 'title': STEP_TITLES[sid]} for sid in _STEPS]


def probe() -> dict:
    binary = binary_path()
    return {
        'ok': True,
        'platform': 'windows' if is_windows() else _paths.system(),
        'frozen': _paths.is_frozen(),
        'binary': str(binary),
        'panelUrl': PANEL_URL,
        'setupSh': (Path(__file__).resolve().parent.parent / 'setup.sh').exists()
                   and not is_windows(),
        'steps': steps(),
        'install': _probe_install(),
        'autostart': _probe_autostart(),
        'shortcut': _probe_shortcut(),
        'keys': _probe_keys(),
        'verify': _probe_verify(),
    }


def preview(step: str) -> dict:
    if step not in _STEPS:
        return {'ok': False, 'error': f'unknown step: {step}'}
    out = _fn(step, 1)()
    out.update({'ok': True, 'step': step})
    return out


def do(step: str, opts: dict | None = None) -> dict:
    if step not in _STEPS:
        return {'ok': False, 'changed': False, 'messages': [f'error|unknown step: {step}']}
    result = _fn(step, 2)(opts or {})
    result['step'] = step
    return result


def undo(step: str) -> dict:
    if step not in _STEPS:
        return {'ok': False, 'changed': False,
                'messages': [f'error|unknown step: {step}']}
    if _STEPS[step][3] is None:
        return {'ok': False, 'changed': False,
                'messages': [f'error|nothing to undo for step: {step} (it writes nothing)']}
    result = _fn(step, 3)()
    result['step'] = step
    return result


def auto(opts: dict | None = None) -> dict:
    """Önerilen kurulum. Başarısız adım **yutulmaz** — `setup.sh --auto`'nun ilk sürümü
    yutuyordu ve kullanıcı kurulumun bittiğini sanıyordu."""
    results, failed = [], []
    for step in AUTO_STEPS:
        result = do(step, opts)
        results.append(result)
        if not result.get('ok'):
            failed.append(step)
    return {'ok': not failed, 'failed': failed, 'results': results}


def uninstall() -> dict:
    """Sihirbazın yazdığı her şeyi geri al. **Anahtarlar ve veri kalır** — onları silmek
    kullanıcının ayrıca isteyeceği bir şeydir, kurulumu geri almanın yan etkisi değil."""
    results = [undo(step) for step in ('shortcut', 'autostart')]
    return {'ok': all(r.get('ok') for r in results), 'results': results,
            'kept': {'keys': str(env_file()) if not is_windows() else 'HKCU\\Environment',
                     'data': [str(_paths.config_dir()), str(_paths.state_dir())]}}


def _run(cmd: list) -> tuple:
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8',
                              errors='replace', timeout=30)
        return proc.returncode, (proc.stdout or '') + (proc.stderr or '')
    except (OSError, subprocess.SubprocessError) as exc:
        return 1, str(exc)


